export function translateLabel(label) {
  return CLASS_NAME_MAP[label] || label || "待识别";
}

export function getDiseaseInfo(label) {
  return DISEASE_INFO[label] || DEFAULT_INFO;
}

export function sanitizeDownloadStem(name) {
  return String(name || "result")
    .replace(/\.[^./\\]+$/, "")
    .replace(/[^A-Za-z0-9\u4e00-\u9fa5._-]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^[_\s.]+|[_\s.]+$/g, "") || "result";
}

export function getVisualizationDownloadName(sourceName, viewMode) {
  const suffix = viewMode === "heatmap" ? "heatmap" : "detections";
  return `${sanitizeDownloadStem(sourceName)}_${suffix}.png`;
}
